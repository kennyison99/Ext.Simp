import { readFile, writeFile } from 'node:fs/promises';

const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const original = await read('../vendor/forum-post-downloader.user.js');
let source = original;
function replaceOnce(from, to) {
  if (source.split(from).length !== 2) throw new Error(`Upstream changed: ${from.slice(0, 80)}`);
  source = source.replace(from, to);
}
// The synchronous GM storage API is hydrated before entering upstream code.
// Its DOM-ready registration must also work after the asynchronous storage read.
replaceOnce("document.addEventListener('DOMContentLoaded', async () => {", 'citylinkOnReady(async () => {');
replaceOnce('ui.tooltip(btnDownloadPost, configForm, {', "ui.tooltip(citylinkCreateOptionsButton(btnDownloadPost), configForm, {\n                        trigger: 'click',");
replaceOnce('ui.tooltip(btnDownloadPage, ui.forms.config.page.createForm(color, html), {', "ui.tooltip(citylinkCreateOptionsButton(btnDownloadPage), ui.forms.config.page.createForm(color, html), {\n                trigger: 'click',");
replaceOnce("await h.http.get('https://api.redgifs.com/v2/auth/temporary', {}, {}, 'text')", "await h.http.get('https://api.redgifs.com/v2/auth/temporary', {}, { __xfpd_timeout: 5000 }, 'text')");
const start = source.indexOf('        const getGenerateWT = async (force = false) => {');
const end = source.indexOf('        const computeWebsiteToken = async', start);
if (start < 0 || end < 0) throw new Error('GoFile adapter anchor missing');
source = source.slice(0, start) +
  '        // MV3: local, reviewed token algorithm; no remote-code execution.\n' +
  '        const getGenerateWT = async () => window.citylinkGenerateWT;\n\n' + source.slice(end);
if (/new Function\s*\(|\beval\s*\(/.test(source)) throw new Error('Unexpected dynamic execution in upstream');
source = '// Generated by scripts/build-downloader.mjs. Edit adapters/build script, not this file.\n' +
  '(async () => {\nawait window.citylinkGMReady;\n' +
  `window.GM_info.script.version = ${JSON.stringify(original.match(/^\/\/ @version (.+)$/m)[1].trim())};\n` + source +
  '\n})().catch(error => console.error("[CityLink] Downloader failed to start", error));\n';
await writeFile(new URL('../src/downloader.js', import.meta.url), source);

const matches = [...original.matchAll(/^\/\/ @match (.+)$/gm)].map(m => m[1].trim());
const domains = [...new Set([
  ...[...original.matchAll(/^\/\/ @connect (.+)$/gm)].map(m => m[1].trim()).filter(d => d !== 'self'),
  ...matches.map(m => new URL(m.replace('*.', '')).hostname),
])].sort();
await writeFile(new URL('../src/download-hosts.js', import.meta.url),
  '// Generated from upstream @connect and @match metadata.\nexport const HOSTS = ' + JSON.stringify(domains, null, 2) + ';\n');
const manifest = JSON.parse(await read('../manifest.json'));
manifest.content_scripts.find(entry => entry.js?.includes('src/downloader.js')).matches = matches;
manifest.host_permissions = domains.flatMap(host => [`https://*.${host}/*`, `http://*.${host}/*`]);
await writeFile(new URL('../manifest.json', import.meta.url), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Built downloader with ${domains.length} permitted host families.`);
